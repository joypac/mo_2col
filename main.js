function shuffle(arr) {
  var a = arr.slice();
  for (var i = a.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

var DIRS = [[-1,0],[1,0],[0,-1],[0,1]];

// Project order is fixed for the session (shuffled once on load) so that
// the same project never appears first in one grid and last in the next.
var sessionProjectOrder = shuffle(projects.map(function(_, i) { return i; }));

var preloadedHeroImages = Object.create(null);
var imageCache = [];

function warmImageCache() {
  var seen = Object.create(null);
  var allMedia = projects.reduce(function(acc, p) { return acc.concat(p.media); }, mixMedia.slice());
  allMedia.forEach(function(item) {
    if (item.type !== 'img') return;
    if (seen[item.src]) return;
    seen[item.src] = true;
    var img = new Image();
    img.decoding = 'async';
    img.loading = 'eager';
    img.src = item.src;
    imageCache.push(img);
  });
}

function setIntrinsicDimensions(el, src) {
  var dims = mediaDimensions[src];
  if (!dims) return;
  el.width = dims[0];
  el.height = dims[1];
  el.style.aspectRatio = dims[0] + ' / ' + dims[1];
}

function preloadHeroImage(src) {
  if (!src || preloadedHeroImages[src]) return;
  preloadedHeroImages[src] = true;

  var link = document.createElement('link');
  link.rel = 'preload';
  link.as = 'image';
  link.href = src;
  document.head.appendChild(link);
}

