/* ── Grid recycler ───────────────────────────────────────
   Removes children from grids that scroll far off-screen
   (beyond 3× viewport height). Preserves height with a
   placeholder so scroll position stays stable. Restores
   content when the grid comes back into range.
── */
var gridRecycler = (function() {
  var savedGrids = new WeakMap();

  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(entry) {
      var grid = entry.target;
      if (entry.isIntersecting) {
        var saved = savedGrids.get(grid);
        if (!saved) return;
        savedGrids.delete(grid);
        grid.style.minHeight = '';
        buildMosaicLayout(grid);
      } else {
        if (savedGrids.has(grid)) return;
        var h = grid.getBoundingClientRect().height;
        savedGrids.set(grid, true);
        var vids = grid.querySelectorAll('.is-video');
        for (var i = 0; i < vids.length; i++) vidObs.unobserve(vids[i]);
        grid.innerHTML = '';
        grid.style.minHeight = h + 'px';
      }
    });
  }, {
    rootMargin: (window.innerHeight * 3) + 'px 0px'
  });

  return {
    observe: function(grid) { obs.observe(grid); }
  };
})();

// Include the first grid in the recycler.
gridRecycler.observe(mosaicEl);

function dynamicRootMargin() {
  return Math.max(400, Math.round(window.innerHeight * 1.5)) + 'px';
}

var infiniteObs = null;
function setupInfiniteObserver() {
  if (infiniteObs) infiniteObs.disconnect();
  infiniteObs = new IntersectionObserver(function(entries) {
    if (!entries[0].isIntersecting) return;
    appendGrid();
  }, { rootMargin: dynamicRootMargin() });
  infiniteObs.observe(sentinel);
}

setupInfiniteObserver();

// Keeps enough content ahead so frame jumps do not hit the page end.
function ensureContentAhead(minAheadPx) {
  var maxScroll = Math.max(0, document.documentElement.scrollHeight - window.innerHeight);
  var remaining = maxScroll - window.scrollY;
  var attempts = 0;

  while (remaining < minAheadPx && attempts < 3) {
    appendGrid();
    maxScroll = Math.max(0, document.documentElement.scrollHeight - window.innerHeight);
    remaining = maxScroll - window.scrollY;
    attempts++;
  }
}

var ContactOverlay = (function() {
  var overlay = document.getElementById('contact-overlay');
  var panel = document.getElementById('contact-panel');
  var trigger = document.getElementById('contact-trigger');
  var sections = Array.prototype.slice.call(panel.querySelectorAll('.contact-section'));
  var toggles = Array.prototype.slice.call(panel.querySelectorAll('.contact-section-toggle'));
  var open = false;

  function setOpenSection(nextIndex) {
    sections.forEach(function(section, idx) {
      var isOpenSection = nextIndex > -1 && idx === nextIndex;
      section.classList.toggle('is-open', isOpenSection);
    });

    toggles.forEach(function(toggle, idx) {
      toggle.setAttribute('aria-expanded', nextIndex > -1 && idx === nextIndex ? 'true' : 'false');
    });
  }

  function positionPanelBelowTrigger() {
    var rect = trigger.getBoundingClientRect();
    var top = Math.round(rect.bottom - 5);
    panel.style.top = top + 'px';

    if (window.innerWidth <= 720) {
      panel.style.left = '';
      panel.style.right = '';
    } else {
      var triggerStyles = window.getComputedStyle(trigger);
      var textStartX = rect.left + parseFloat(triggerStyles.paddingLeft || '0');
      var left = Math.max(8, Math.round(textStartX));
      panel.style.left = left + 'px';
      panel.style.right = '';
    }
  }

  function syncA11y() {
    overlay.setAttribute('aria-hidden', open ? 'false' : 'true');
    trigger.setAttribute('aria-expanded', open ? 'true' : 'false');
  }

  function openOverlay() {
    if (open) return;
    open = true;
    var contents = Array.prototype.slice.call(panel.querySelectorAll('.contact-section-content'));
    contents.forEach(function(el) { el.style.transition = 'none'; });
    setOpenSection(-1);
    requestAnimationFrame(function() {
      contents.forEach(function(el) { el.style.transition = ''; });
    });
    overlay.style.willChange = 'clip-path';
    overlay.classList.add('is-open');
    positionPanelBelowTrigger();
    syncA11y();
    setTimeout(function() {
      panel.focus();
    }, 0);
  }

  function closeOverlay() {
    if (!open) return;
    open = false;
    overlay.classList.remove('is-open');
    syncA11y();
    trigger.focus();
    overlay.addEventListener('transitionend', function cleanup() {
      overlay.removeEventListener('transitionend', cleanup);
      if (!open) overlay.style.willChange = '';
    });
  }

  function toggleOverlay() {
    if (open) closeOverlay();
    else openOverlay();
  }

  trigger.addEventListener('click', function(e) {
    e.stopPropagation();
    toggleOverlay();
  });

  overlay.addEventListener('click', function(e) {
    var rect = panel.getBoundingClientRect();
    var margin = 28;
    var insideSafeArea =
      e.clientX >= rect.left - margin &&
      e.clientX <= rect.right + margin &&
      e.clientY >= rect.top - margin &&
      e.clientY <= rect.bottom + margin;

    if (insideSafeArea) return;
    closeOverlay();
  });

  panel.addEventListener('click', function(e) {
    e.stopPropagation();
  });

  var switching = false;

  function switchSection(nextIndex) {
    if (switching) return;
    switching = true;
    panel.style.transition = 'opacity 500ms ease-out';
    panel.style.opacity = '0';
    setTimeout(function() {
      setOpenSection(nextIndex);
      requestAnimationFrame(function() {
        requestAnimationFrame(function() {
          panel.style.transition = 'opacity 900ms cubic-bezier(0.25, 0, 0.2, 1)';
          panel.style.opacity = '1';
          setTimeout(function() {
            panel.style.transition = '';
            panel.style.opacity = '';
            switching = false;
          }, 900);
        });
      });
    }, 500);
  }

  toggles.forEach(function(toggle, idx) {
    toggle.addEventListener('click', function(e) {
      e.stopPropagation();
      var section = sections[idx];
      var willOpen = !section.classList.contains('is-open');
      switchSection(willOpen ? idx : -1);
    });
  });

  window.addEventListener('resize', function() {
    if (!open) return;
    positionPanelBelowTrigger();
  }, { passive: true });

  window.addEventListener('orientationchange', function() {
    if (!open) return;
    positionPanelBelowTrigger();
  }, { passive: true });

  return {
    isOpen: function() { return open; },
    open: openOverlay,
    close: closeOverlay,
    toggle: toggleOverlay
  };
})();

var skipFirstNav = false;

var FrameNavigator = (function() {
  var smooth = false;
  var lockUntil = 0;
  var lockTimer = 0;
  var lockMsSmooth = 1520;
  var lockMsInstant = 1500;
  var touchStartY = 0;
  var touchStartX = 0;
  var touchMoved = false;
  var touchStartedOnInteractive = false;
  var lastTouchNavTs = 0;
  var resizeTimer = 0;

  function targetToElement(target) {
    if (!target) return null;
    if (target.nodeType === 1) return target;
    if (target.nodeType === 3) return target.parentElement;
    return null;
  }

  function isInteractiveTarget(target) {
    var el = targetToElement(target);
    return !!(el && el.closest('a, button, input, textarea, select, label, #contact-trigger, #contact-panel, #contact-overlay, .contact-section-toggle, .contact-link'));
  }

  function viewportStep() {
    return Math.max(1, window.innerHeight || 1);
  }

  function maxScrollY() {
    return Math.max(0, document.documentElement.scrollHeight - window.innerHeight);
  }

  function lockForTransition() {
    var now = Date.now();
    var ms = smooth ? lockMsSmooth : lockMsInstant;
    lockUntil = now + ms;
    clearTimeout(lockTimer);
    lockTimer = setTimeout(function() {
      lockUntil = 0;
    }, ms + 20);
  }

  function isLocked() {
    return Date.now() < lockUntil;
  }

  function scrollToY(yTarget) {
    window.scrollTo({ top: yTarget, behavior: smooth ? 'smooth' : 'auto' });
  }

  var frameFadeEl = document.getElementById('frame-fade');

  function goByDirection(direction) {
    if (ContactOverlay.isOpen()) return;
    if (isLocked()) return;

    ensureContentAhead(window.innerHeight * 2.5);

    var step = viewportStep();
    var currentPos = window.scrollY;
    var target = currentPos + (direction * step);
    var maxY = maxScrollY();

    if (target < 0) target = 0;
    if (target > maxY) {
      ensureContentAhead(window.innerHeight * 3);
      maxY = maxScrollY();
      target = Math.min(target, maxY);
    }

    lockForTransition();
    frameFadeEl.style.transition = 'opacity 500ms ease-out';
    frameFadeEl.style.opacity = '1';
    setTimeout(function() {
      scrollToY(target);
      frameFadeEl.style.transition = 'opacity 900ms cubic-bezier(0.25, 0, 0.2, 1)';
      frameFadeEl.style.opacity = '0';
    }, 500);
  }

  function goDown() {
    goByDirection(1);
  }

  function goUp() {
    goByDirection(-1);
  }

  function snapToNearestFrame() {
    var step = viewportStep();
    var current = window.scrollY;
    var snapped = Math.round(current / step) * step;
    var maxY = maxScrollY();
    if (snapped > maxY) snapped = maxY;

    var previousSmooth = smooth;
    smooth = false;
    scrollToY(snapped);
    smooth = previousSmooth;
  }

  function onWheel(e) {
    e.preventDefault();
    // Wheel scrolling is fully disabled by request.
  }

  function onClick(e) {
    if (ContactOverlay.isOpen()) return;

    if (Date.now() - lastTouchNavTs < 420) return;
    if (e.button !== 0) return;
    if (e.defaultPrevented) return;

    var target = targetToElement(e.target);
    if (target && target.closest && target.closest('a, button, input, textarea, select, label')) return;
    goDown();
  }

  function onTouchStart(e) {
    if (!e.touches || !e.touches[0]) return;
    touchMoved = false;
    touchStartY = e.touches[0].clientY;
    touchStartX = e.touches[0].clientX;
    touchStartedOnInteractive = isInteractiveTarget(e.target);
  }

  function onTouchMove(e) {
    if (touchStartedOnInteractive || ContactOverlay.isOpen()) return;
    if (!e.touches || !e.touches[0]) return;
    var dy = e.touches[0].clientY - touchStartY;
    var dx = e.touches[0].clientX - touchStartX;
    if (Math.abs(dy) > 8 || Math.abs(dx) > 8) touchMoved = true;
    e.preventDefault();
  }

  function onTouchEnd(e) {
    if (ContactOverlay.isOpen()) return;
    if (touchStartedOnInteractive) {
      lastTouchNavTs = Date.now();
      return;
    }

    if (!e.changedTouches || !e.changedTouches[0]) return;
    var dy = e.changedTouches[0].clientY - touchStartY;
    var absDy = Math.abs(dy);

    if (!touchMoved && absDy < 10) {
      if (skipFirstNav) { skipFirstNav = false; }
      else { goDown(); }
    }

    lastTouchNavTs = Date.now();
  }

  function onKeydown(e) {
    if (e.key === 'Escape' && ContactOverlay.isOpen()) {
      e.preventDefault();
      ContactOverlay.close();
      return;
    }

    if (e.key === 'ArrowDown' || e.key === 'PageDown' || e.key === ' ') {
      e.preventDefault();
      goDown();
    } else if (e.key === 'ArrowUp' || e.key === 'PageUp') {
      e.preventDefault();
      goUp();
    } else if (e.key === 'Home') {
      e.preventDefault();
      lockForTransition();
      scrollToY(0);
    } else if (e.key === 'End') {
      e.preventDefault();
      ensureContentAhead(window.innerHeight * 3);
      lockForTransition();
      scrollToY(maxScrollY());
    }
  }

  function onResize() {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(function() {
      setupInfiniteObserver();
      ensureContentAhead(window.innerHeight * 2.5);
      snapToNearestFrame();
    }, 140);
  }

  function init() {
    ensureContentAhead(window.innerHeight * 2.5);
    window.addEventListener('wheel', onWheel, { passive: false });
    document.addEventListener('click', onClick, { passive: true });
    window.addEventListener('touchstart', onTouchStart, { passive: true });
    window.addEventListener('touchmove', onTouchMove, { passive: false });
    window.addEventListener('touchend', onTouchEnd, { passive: true });
    window.addEventListener('keydown', onKeydown);
    window.addEventListener('resize', onResize, { passive: true });
    window.addEventListener('orientationchange', onResize, { passive: true });
  }

  return {
    init: init,
    goDown: goDown,
    goUp: goUp,
    setSmooth: function(value) {
      smooth = !!value;
    },
    isSmooth: function() {
      return smooth;
    }
  };
})();

FrameNavigator.init();
window.ContactOverlay = ContactOverlay;
window.FrameNavigator = FrameNavigator;

