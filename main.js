function buildMosaicLayout(container, isFirst) {
  var isMobile = window.innerWidth <= 600;
  var COLS = isMobile ? 2 : 3;

  container.innerHTML = '';
  container.classList.add('mosaic-engine-blob');

  var rhythmPhase = Math.random() < 0.5 ? 0 : 1;
  function bumpRhythm() {
    container.setAttribute('data-mosaic-rhythm', (rhythmPhase++ % 2 === 0) ? 'a' : 'b');
  }

  var order = sessionProjectOrder.slice();
  // If there is any video project, always put one first (user preference).
  // This is session-stable because `order` is session-stable.
  for (var vi = 0; vi < order.length; vi++) {
    if (projects[order[vi]].media.some(function(m) { return m.type === 'vid'; })) {
      if (vi > 0) order.unshift(order.splice(vi, 1)[0]);
      break;
    }
  }

  var mixPool = desimilarize(shuffle(mixMedia.slice()));
  var mixPos = 0;

  function nextMixSlice() {
    if (mixPos >= mixPool.length) return [];
    // Bias to 1 item ("quase sempre") with occasional 2 ("muitas vezes").
    // Max 2 consecutive — editorial constraint.
    var n = Math.random() < 0.25 ? 2 : 1;
    n = Math.min(n, mixPool.length - mixPos);
    if (n < 1) n = 1;
    var sl = mixPool.slice(mixPos, mixPos + n);
    mixPos += sl.length;
    return sl;
  }

  var mediaEmitted = 0;
  var aboveFoldVideoUsed = false;
  var lastStripIdx = -99;

  function renderBlobChunk(items, pi, blobKind, forceHero) {
    if (!items.length) return;
    var wrap = document.createElement('div');
    wrap.className = 'mosaic-blob' + (blobKind === 'mix' ? ' is-mix-blob' : '');
    wrap.setAttribute('data-blob', blobKind);
    container.appendChild(wrap);
    bumpRhythm();

    var isMix = blobKind === 'mix';
    var rows = [];
    // Guarantee (deterministic): on the first grid, the first project blob begins with a row that
    // contains a video (if that project has one). This avoids the "sometimes no video" refresh issue.
    // We do NOT force the video to be the very first cell; we place it off-center with empties.
    if (forceHero && !isMix) {
      var heroVid = extractFirstVideo(items);
      if (heroVid) {
        // Randomize which row of the first viewport gets the hero (0, 1 or 2).
        // Keeps the hero in the first viewport but varies its position session-to-session.
        var heroRowOffset = Math.floor(Math.random() * 3);

        // Generate simple single-photo pre-rows so the hero isn't always row 0.
        // Use non-video items only — keeps videos clustered around the hero.
        function shiftNonVideo() {
          for (var k = 0; k < items.length; k++) {
            if (items[k].type !== 'vid') return items.splice(k, 1)[0];
          }
          return null;
        }
        for (var pr = 0; pr < heroRowOffset; pr++) {
          var preItem = shiftNonVideo();
          if (!preItem) break;
          if (COLS === 3) {
            // 3-col desktop pre-row: photo offset to one side, rest empty
            var sideR = Math.random();
            if (sideR < 0.34) rows.push([{ t: 'm', item: preItem }, { t: 'e' }, { t: 'e' }]);
            else if (sideR < 0.67) rows.push([{ t: 'e' }, { t: 'm', item: preItem }, { t: 'e' }]);
            else rows.push([{ t: 'e' }, { t: 'e' }, { t: 'm', item: preItem }]);
          } else {
            // 2-col mobile pre-row: photo on left or right, other cell empty
            if (Math.random() < 0.5) rows.push([{ t: 'm', item: preItem }, { t: 'e' }]);
            else rows.push([{ t: 'e' }, { t: 'm', item: preItem }]);
          }
        }

        if (COLS === 3) {
          var withCompanion = items.length ? items.shift() : null;
          if (withCompanion) {
            // video in col 2; companion alternates left/right
            if (Math.random() < 0.5) rows.push([{ t: 'm', item: withCompanion }, { t: 'm', item: heroVid }, { t: 'e' }]);
            else rows.push([{ t: 'e' }, { t: 'm', item: heroVid }, { t: 'm', item: withCompanion }]);
          } else {
            rows.push([{ t: 'e' }, { t: 'm', item: heroVid }, { t: 'e' }]);
          }
        } else {
          // 2 cols: place video on left or right (alternating feel with empties)
          if (Math.random() < 0.5) rows.push([{ t: 'e' }, { t: 'm', item: heroVid }]);
          else rows.push([{ t: 'm', item: heroVid }, { t: 'e' }]);
        }
      }
    }

    // Plan the remainder. (Important: plan AFTER any hero extraction so we don't keep stale rows.)
    rows = rows.concat(planBlobRows(items, COLS, isMix));
    var blobRow = 0;
    for (var ri = 0; ri < rows.length; ri++) {
      var row = rows[ri];
      for (var ci = 0; ci < row.length; ci++) {
        var cell = row[ci];
        if (cell.t === 'e') {
          appendEmptyMosaicCell(wrap);
          continue;
        }
        var item = cell.item;
        var wantWide = !!cell.wide && !mosaicPortraitVideo(item);
        var aboveFold = isFirst && mediaEmitted < 4;

        if (blobKind === 'mix') {
          appendMixCell(item, wrap, aboveFold, wantWide);
        } else {
          var div = document.createElement('div');
          div.className = 'mosaic-cell' + (item.type === 'vid' ? ' is-video' : '');
          if (wantWide) div.classList.add('is-wide');

          var strip = null;
          if (blobRow - lastStripIdx >= 2 && Math.random() < 0.32 && projects[pi].media.length > 3) {
            var projImgs = projects[pi].media
              .filter(function(m) { return m.type === 'img'; })
              .map(function(m) { return m.src; });
            if (projImgs.length) {
              lastStripIdx = blobRow;
              strip = document.createElement('div');
              strip.className = 'wide-strip';
              strip.style.height = (6 + Math.random() * 8).toFixed(2) + 'vw';
              var stripImg = document.createElement('img');
              var stripSrc = projImgs[Math.floor(Math.random() * projImgs.length)];
              stripImg.className = 'mosaic-media is-strip-media';
              stripImg.decoding = 'async';
              stripImg.setAttribute('loading', 'lazy');
              stripImg.setAttribute('fetchpriority', 'low');
              setIntrinsicDimensions(stripImg, stripSrc);
              stripImg.alt = '';
              stripImg.addEventListener('load', function() {
                markMediaLoaded(this.closest('.mosaic-cell'), this);
              }, { once: true });
              stripImg.addEventListener('error', function() {
                markMediaLoaded(this.closest('.mosaic-cell'), this);
              }, { once: true });
              stripImg.src = stripSrc;
              strip.appendChild(stripImg);
            }
          }

          var stripAbove = strip && Math.random() < 0.5;

          if (item.type === 'vid') {
            var video = document.createElement('video');
            video.className = 'mosaic-media';
            setIntrinsicDimensions(video, item.src);
            video.muted = true;
            video.loop  = true;
            video.setAttribute('playsinline', '');
            var preloadMode = 'none';
            if (aboveFold && !aboveFoldVideoUsed) {
              preloadMode = 'metadata';
              aboveFoldVideoUsed = true;
            }
            video.setAttribute('preload', preloadMode);
            video.addEventListener('loadeddata', function() {
              markMediaLoaded(this.closest('.mosaic-cell'), this);
            }, { once: true });
            video.addEventListener('error', function() {
              markMediaLoaded(this.closest('.mosaic-cell'), this);
            }, { once: true });
            var vsrc = document.createElement('source');
            vsrc.src = item.src;
            video.appendChild(vsrc);
            if (stripAbove) div.appendChild(strip);
            div.appendChild(video);
            if (strip && !stripAbove) div.appendChild(strip);
            vidObs.observe(div);
          } else {
            var img = document.createElement('img');
            img.className = 'mosaic-media';
            img.decoding = 'async';
            setIntrinsicDimensions(img, item.src);
            img.alt = projects[pi].name;
            img.setAttribute('loading', aboveFold ? 'eager' : 'lazy');
            if (aboveFold) {
              img.setAttribute('fetchpriority', 'high');
              preloadHeroImage(item.src);
            } else {
              img.setAttribute('fetchpriority', 'low');
            }
            img.addEventListener('load', function() {
              markMediaLoaded(this.closest('.mosaic-cell'), this);
            }, { once: true });
            img.addEventListener('error', function() {
              markMediaLoaded(this.closest('.mosaic-cell'), this);
            }, { once: true });
            img.src = item.src;
            if (stripAbove) div.appendChild(strip);
            div.appendChild(img);
            if (strip && !stripAbove) div.appendChild(strip);
          }

          var label = document.createElement('span');
          label.className = 'mosaic-label';
          label.textContent = projects[pi].name;
          div.appendChild(label);

          wrap.appendChild(div);
        }
        mediaEmitted++;
      }
      blobRow++;
    }
  }

  // Probability of interrupting a project mid-way with a mix slice.
  // Mix only interrupts if the project has enough media to make a split meaningful.
  var MIX_INSIDE_PROJECT_PROB = 0.45;

  function renderProjectMaybeInterrupted(media, pi, forceHero) {
    // First project (hero) renders whole — keep the opening clean, no mix in
    // the first viewport. Short projects also render whole (no room to split).
    if (forceHero || media.length < 5 || Math.random() >= MIX_INSIDE_PROJECT_PROB) {
      renderBlobChunk(media, pi, 'project', forceHero);
      return;
    }

    // Pick a split point that leaves at least 2 items on each side.
    var splitAt = 2 + Math.floor(Math.random() * (media.length - 3));
    var firstChunk = media.slice(0, splitAt);
    var secondChunk = media.slice(splitAt);

    renderBlobChunk(firstChunk, pi, 'project', forceHero);

    var interruptMix = nextMixSlice();
    if (interruptMix.length) {
      renderBlobChunk(interruptMix, pi, 'mix', false);
    }

    renderBlobChunk(secondChunk, pi, 'project', false);
  }

  for (var si = 0; si < order.length; si++) {
    var pi = order[si];
    var media = prepareMediaForProject(pi, isMobile);
    // First grid: the blob renderer will enforce a video row in the first viewport (if any exists).

    renderProjectMaybeInterrupted(media, pi, isFirst && si === 0);

    if (si < order.length - 1) {
      if (Math.random() < 0.62) appendMosaicBreather(container, isMobile);
      var mixChunk = nextMixSlice();
      if (mixChunk.length) {
        renderBlobChunk(mixChunk, pi, 'mix', false);
        if (Math.random() < 0.55) appendMosaicBreather(container, isMobile);
      }
    }
  }

  while (mixPos < mixPool.length) {
    var rest = nextMixSlice();
    if (!rest.length) break;
    if (Math.random() < 0.5) appendMosaicBreather(container, isMobile);
    renderBlobChunk(rest, -1, 'mix', false);
  }
}

